/**
 * The single source of truth for every component. The docs sidebar, the
 * components index, the CLI registry and the tests all read from this list,
 * and `demos.ts` is type-checked against it.
 */
export const CATEGORIES = [
  "Navigation",
  "Actions",
  "Data Display",
  "Backgrounds",
  "Three.js",
  "Typography",
  "Sections",
  "Components",
] as const;

export type Category = (typeof CATEGORIES)[number];

/** One live control in the docs preview; `key` is the component prop it drives. */
export type PreviewControl =
  | {
      kind: "range";
      key: string;
      label: string;
      min: number;
      max: number;
      step: number;
      default: number;
    }
  | {
      kind: "choice";
      key: string;
      label: string;
      options: readonly { value: string; label: string }[];
      default: string;
    }
  | { kind: "color"; key: string; label: string; default: string }
  | { kind: "text"; key: string; label: string; default: string };

export interface RegistryItem {
  /** Slug used in URLs, file names and `npx @modus-ui/cli add <name>`. */
  name: string;
  title: string;
  category: Category;
  type: "components:ui";
  dependencies: readonly string[];
  files: readonly string[];
  /** Live controls shown under the docs preview. The demo forwards them to the component. */
  controls?: readonly PreviewControl[];
}

